function item(
  id: string,
  day: number | null,
  category: LineItem["category"],
  description: string,
  qty: number,
  unit: LineItem["unit"],
  unitPrice: number,
  currency: LineItem["currency"],
): LineItem {
  return { id, day, category, description, qty, unit, unitPrice, currency };
}

function laid(
  total: number,
  rows: Array<{
    id: string;
    label: string;
    due: string;
    weight: number;
    status: Installment["status"];
    method?: PayMethod;
    paidAt?: string;
    receiptNo?: string;
    reference?: string;
  }>,
): Installment[] {
  const amounts = splitTotal(total, rows.map((row) => row.weight));
  return rows.map((row, index) => ({
    id: row.id,
    label: row.label,
    due: row.due,
    amount: amounts[index],
    status: row.status,
    method: row.method,
    paidAt: row.paidAt,
    receiptNo: row.receiptNo,
    reference: row.reference,
  }));
}

